#!/usr/bin/env python3
"""PreToolUse hook on Edit|Write.

Enforces the invariants in CLAUDE.md that a prompt instruction cannot guarantee.
Exit 2 blocks the edit; stderr is fed back to Claude as the reason.

Written in Python rather than bash+jq so it has no dependency this repo does not
already have.
"""

from __future__ import annotations

import json
import os
import re
import sys


def block(reason: str) -> None:
    print(f"BLOCKED: {reason}", file=sys.stderr)
    sys.exit(2)


def main() -> None:
    try:
        payload = json.load(sys.stdin)
    except json.JSONDecodeError:
        sys.exit(0)  # never break the session on a parse failure

    tool_input = payload.get("tool_input") or {}
    path = (tool_input.get("file_path") or "").replace("\\", "/")
    if not path:
        sys.exit(0)

    new = tool_input.get("content") or tool_input.get("new_string") or ""
    exists = os.path.exists(path)

    # 1. Applied migrations are immutable.
    if re.search(r"(^|/)migrations/[^/]+\.sql$", path) and exists:
        block(
            "migrations are forward-only. "
            f"{path} already exists; add a new numbered migration instead."
        )

    # 2. No wall-clock time in the ledger (core 5.3).
    if re.search(r"(^|/)harness/ledger/.*\.py$", path):
        if re.search(r"\b(datetime\.now|datetime\.utcnow|time\.time)\s*\(", new):
            block(
                "harness/ledger takes time from Postgres now(), never the Python clock. "
                "Clock skew between workers is real (core 5.3, rule 40)."
            )

    # 3. Banned vocabulary in source (core 3.2, 3.3). Prose is fine; class names are not.
    if path.endswith(".py"):
        banned = r"class\s+\w*(Orchestrator|Coordinator|Manager|Controller|Router|Supervisor)\b"
        if re.search(banned, new):
            block(
                "banned role name. If a class wants one of these names the design is wrong "
                "(core 3.3). Raise it rather than renaming around it."
            )
        if re.search(r"\bTaskCard\b", new):
            block(
                "it is 'task' in code; 'card' is prose only. "
                "Never TaskCard, never a cards table (core 3.2)."
            )

    # 4. Rule 63: no new design documents.
    if re.search(r"(^|/)docs/[^/]+\.md$", path) and not exists:
        block(
            "rule 63: no new design documents. Land this in an existing doc, "
            "a new ADR under docs/adr/, or docs/rules-and-risks.md."
        )

    # 5. Generated Odoo files are generated (rule 78).
    if path.endswith("/__manifest__.py") or re.search(r"/addons/[^/]+/__init__\.py$", path):
        block(
            f"{path} is generated by hooks/regenerate_manifest.py. "
            "A card needing a dependency emits spec_conflict (rule 78)."
        )

    sys.exit(0)


if __name__ == "__main__":
    main()
