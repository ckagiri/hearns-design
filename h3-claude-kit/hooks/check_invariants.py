#!/usr/bin/env python3
"""Pre-commit check: the H3 invariants, applied to staged files.

This duplicates .claude/hooks/guard_invariants.py deliberately. That hook only sees
edits Claude makes; this one sees every commit, including hand edits and anything a
Bash command wrote. The overlap is the point.
"""

from __future__ import annotations

import re
import sys

FAILURES: list[str] = []

CLOCK = re.compile(r"\b(datetime\.now|datetime\.utcnow|time\.time)\s*\(")
BANNED_CLASS = re.compile(
    r"class\s+\w*(Orchestrator|Coordinator|Manager|Controller|Router|Supervisor)\b"
)
TASK_CARD = re.compile(r"\bTaskCard\b")
CARDS_TABLE = re.compile(r"CREATE\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?cards\b", re.I)


def check(path: str) -> None:
    try:
        text = open(path, encoding="utf-8").read()
    except (OSError, UnicodeDecodeError):
        return

    norm = path.replace("\\", "/")

    if "/harness/ledger/" in f"/{norm}" and norm.endswith(".py"):
        if CLOCK.search(text):
            FAILURES.append(
                f"{path}: harness/ledger takes time from Postgres now(), not the Python "
                f"clock. Clock skew between workers is real (core 5.3)."
            )

    if norm.endswith(".py"):
        if BANNED_CLASS.search(text):
            FAILURES.append(
                f"{path}: banned role name. If a class wants one of these names the design "
                f"is wrong (core 3.3)."
            )
        if TASK_CARD.search(text):
            FAILURES.append(f"{path}: it is 'task' in code; 'card' is prose only (core 3.2).")

    if norm.endswith(".sql") and CARDS_TABLE.search(text):
        FAILURES.append(f"{path}: there is no cards table. The table is 'tasks' (core 3.2).")

    if norm.endswith("/__manifest__.py") or re.search(r"/addons/[^/]+/__init__\.py$", norm):
        FAILURES.append(
            f"{path} is generated by hooks/regenerate_manifest.py. A card needing a "
            f"dependency emits spec_conflict (rule 78)."
        )


def main() -> int:
    for path in sys.argv[1:]:
        check(path)
    for f in FAILURES:
        print(f"BLOCKED: {f}", file=sys.stderr)
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
